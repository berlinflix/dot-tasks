package dev.suyash.dot.core.designsystem.dotmatrix

/**
 * A 5×7 dot-matrix font (original glyphs, drawn on a grid — no font licensing involved).
 * Each glyph is 7 rows of equal-width strings where `#` is a lit dot.
 * Lower-case input is upper-cased; unknown characters render as a blank cell.
 */
object DotMatrixFont {
    const val ROWS = 7
    const val GAP_COLUMNS = 1

    class Glyph(val columns: Int, private val bits: BooleanArray) {
        fun isLit(row: Int, column: Int): Boolean = bits[row * columns + column]
    }

    private val glyphs: Map<Char, Glyph> = buildMap {
        fun g(char: Char, vararg rows: String) {
            require(rows.size == ROWS) { "Glyph '$char' must have $ROWS rows" }
            val width = rows.first().length
            require(rows.all { it.length == width }) { "Glyph '$char' rows differ in width" }
            put(char, Glyph(width, BooleanArray(width * ROWS) { rows[it / width][it % width] == '#' }))
        }

        g('0', ".###.", "#...#", "#..##", "#.#.#", "##..#", "#...#", ".###.")
        g('1', "..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###.")
        g('2', ".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####")
        g('3', "#####", "...#.", "..#..", "...#.", "....#", "#...#", ".###.")
        g('4', "...#.", "..##.", ".#.#.", "#..#.", "#####", "...#.", "...#.")
        g('5', "#####", "#....", "####.", "....#", "....#", "#...#", ".###.")
        g('6', "..##.", ".#...", "#....", "####.", "#...#", "#...#", ".###.")
        g('7', "#####", "....#", "...#.", "..#..", ".#...", ".#...", ".#...")
        g('8', ".###.", "#...#", "#...#", ".###.", "#...#", "#...#", ".###.")
        g('9', ".###.", "#...#", "#...#", ".####", "....#", "...#.", ".##..")

        g('A', ".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#")
        g('B', "####.", "#...#", "#...#", "####.", "#...#", "#...#", "####.")
        g('C', ".###.", "#...#", "#....", "#....", "#....", "#...#", ".###.")
        g('D', "###..", "#..#.", "#...#", "#...#", "#...#", "#..#.", "###..")
        g('E', "#####", "#....", "#....", "####.", "#....", "#....", "#####")
        g('F', "#####", "#....", "#....", "####.", "#....", "#....", "#....")
        g('G', ".###.", "#...#", "#....", "#.###", "#...#", "#...#", ".####")
        g('H', "#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#")
        g('I', ".###.", "..#..", "..#..", "..#..", "..#..", "..#..", ".###.")
        g('J', "..###", "...#.", "...#.", "...#.", "...#.", "#..#.", ".##..")
        g('K', "#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#")
        g('L', "#....", "#....", "#....", "#....", "#....", "#....", "#####")
        g('M', "#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#")
        g('N', "#...#", "#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#")
        g('O', ".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###.")
        g('P', "####.", "#...#", "#...#", "####.", "#....", "#....", "#....")
        g('Q', ".###.", "#...#", "#...#", "#...#", "#.#.#", "#..#.", ".##.#")
        g('R', "####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#")
        g('S', ".####", "#....", "#....", ".###.", "....#", "....#", "####.")
        g('T', "#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#..")
        g('U', "#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###.")
        g('V', "#...#", "#...#", "#...#", "#...#", "#...#", ".#.#.", "..#..")
        g('W', "#...#", "#...#", "#...#", "#.#.#", "#.#.#", "#.#.#", ".#.#.")
        g('X', "#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#")
        g('Y', "#...#", "#...#", "#...#", ".#.#.", "..#..", "..#..", "..#..")
        g('Z', "#####", "....#", "...#.", "..#..", ".#...", "#....", "#####")

        g(' ', "...", "...", "...", "...", "...", "...", "...")
        g(':', ".", ".", "#", ".", "#", ".", ".")
        g('.', ".", ".", ".", ".", ".", ".", "#")
        g(',', "..", "..", "..", "..", "..", ".#", "#.")
        g('\'', "#", "#", ".", ".", ".", ".", ".")
        g('·', ".", ".", ".", "#", ".", ".", ".")
        g('-', "...", "...", "...", "###", "...", "...", "...")
        g('+', ".....", "..#..", "..#..", "#####", "..#..", "..#..", ".....")
        g('/', "....#", "....#", "...#.", "..#..", ".#...", "#....", "#....")
        g('!', "#", "#", "#", "#", "#", ".", "#")
        g('?', ".###.", "#...#", "....#", "...#.", "..#..", ".....", "..#..")
        g('%', "##..#", "##..#", "...#.", "..#..", ".#...", "#..##", "#..##")
        g('&', ".##..", "#..#.", "#.#..", ".#...", "#.#.#", "#..#.", ".##.#")
        g('(', "..#", ".#.", "#..", "#..", "#..", ".#.", "..#")
        g(')', "#..", ".#.", "..#", "..#", "..#", ".#.", "#..")
    }

    private val blank = glyphs.getValue(' ')

    fun glyph(char: Char): Glyph = glyphs[char.uppercaseChar()] ?: blank

    /** Total columns needed to draw [text], including one blank column between glyphs. */
    fun columns(text: String): Int =
        if (text.isEmpty()) 0 else text.sumOf { glyph(it).columns } + GAP_COLUMNS * (text.length - 1)

    /** Calls [onDot] for every cell of [text]: (column, row, lit). */
    inline fun forEachDot(text: String, onDot: (column: Int, row: Int, lit: Boolean) -> Unit) {
        var x = 0
        text.forEachIndexed { index, char ->
            val glyph = glyph(char)
            for (row in 0 until ROWS) {
                for (col in 0 until glyph.columns) onDot(x + col, row, glyph.isLit(row, col))
            }
            x += glyph.columns
            if (index != text.lastIndex) {
                for (row in 0 until ROWS) onDot(x, row, false)
                x += GAP_COLUMNS
            }
        }
    }
}
